// Mantem a estrutura PostgreSQL equivalente ao schema SQLite legado.
// O arquivo gerado e versionado e executado no Supabase antes do deploy.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
let sql = readFileSync(join(root, "lib", "schema.sql"), "utf8");
sql = sql.replace(/^PRAGMA[^\r\n]*\r?\n/gm, "");
sql = sql.replace(/INTEGER PRIMARY KEY AUTOINCREMENT/g, "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
sql = sql.replace(/\bREAL\b/g, "NUMERIC");
sql = sql.replace(/\bVIRTUAL\b/g, "STORED");
sql = sql.replace(/datetime\('now','localtime'\)/g,
  "to_char(CURRENT_TIMESTAMP AT TIME ZONE 'America/Sao_Paulo', 'YYYY-MM-DD HH24:MI:SS')");
sql = sql.replace(/date\('now','localtime'\)/g,
  "to_char(CURRENT_TIMESTAMP AT TIME ZONE 'America/Sao_Paulo', 'YYYY-MM-DD')");
sql = sql.replace(/CAST\(julianday\('now'\) - julianday\(MAX\(v\.data\)\) AS INTEGER\)/g,
  "((CURRENT_TIMESTAMP AT TIME ZONE 'America/Sao_Paulo')::date - MAX(v.data)::date)");
sql = sql.replace(/^DROP VIEW IF EXISTS \w+;\r?\n/gm, "");
sql = sql.replace(/CREATE VIEW /g, "CREATE OR REPLACE VIEW ");
sql = sql.replace(/SQLite \/ node:sqlite/, "PostgreSQL / Supabase");
// SQLite aceita REFERENCES para tabela declarada adiante; PostgreSQL exige a
// tabela de destino antes. Ordena tabelas por dependencias e depois indices.
const tables = new Map();
sql = sql.replace(/CREATE TABLE IF NOT EXISTS\s+(\w+)\s*\([\s\S]*?^\);/gm, (definition, name) => {
  tables.set(name, definition);
  return "";
});
const indexes = [];
sql = sql.replace(/^CREATE (?:UNIQUE )?INDEX IF NOT EXISTS[^;]*;/gm, (definition) => {
  indexes.push(definition);
  return "";
});
const ordered = [];
while (tables.size) {
  let progressed = false;
  for (const [name, definition] of tables) {
    const dependencies = [...definition.matchAll(/REFERENCES\s+(\w+)\s*\(/g)]
      .map((match) => match[1]).filter((reference) => reference !== name);
    if (dependencies.some((reference) => tables.has(reference))) continue;
    ordered.push(definition);
    tables.delete(name);
    progressed = true;
  }
  if (!progressed) throw new Error(`Dependencia circular no schema: ${[...tables.keys()].join(", ")}`);
}
sql = `${ordered.join("\n\n")}\n\n${indexes.join("\n")}\n\n${sql}`;
const header = `-- Banco isolado do restante do projeto Supabase.\n-- Executar no SQL Editor ou via npm run db:migrar.\nBEGIN;\nCREATE SCHEMA IF NOT EXISTS banho_encanto;\nSET LOCAL search_path = banho_encanto, pg_catalog;\n\n`;
const footer = `\n-- Somente a aplicacao (conexao postgres) acessa este schema; a Data API\n-- publica o schema public, nao o banho_encanto.\nCOMMIT;\n`;
writeFileSync(join(root, "lib", "schema-postgres.sql"), header + sql.trim() + footer);
console.log("lib/schema-postgres.sql gerado");
